use anyhow::{Context, Result};
use chrono::Utc;
use std::fs;
use std::process::Command;
use tracing::{info, error};

pub struct DreamWeaver {
    output_dir: String,
    mod_file: String,
}

impl DreamWeaver {
    pub fn new() -> Self {
        let output_dir = "src/dreams".to_string();
        let mod_file = "src/dreams/mod.rs".to_string();
        
        fs::create_dir_all(&output_dir).ok();
        if fs::metadata(&mod_file).is_err() {
            fs::write(&mod_file, "// WENDY Autonomous Dream Registry\n").ok();
        }
        
        Self { output_dir, mod_file }
    }

    pub fn materialize_dream(&self, dream_name: &str, symbolic_logic: &str) -> Result<()> {
        let zulu_time = Utc::now().format("%Y-%m-%dT%H:%M:%S%.3fZ").to_string();
        info!(timestamp = %zulu_time, dream = %dream_name, "Materializing symbolic dream...");

        let file_path = format!("{}/{}.rs", self.output_dir, dream_name);
        
        let rust_code = format!(
            r#"//! Autonomous module generated by WENDY at {}
//! Dream: {}
#![allow(dead_code)]

use crate::symbolic::{{Symbol, SymbolicEngine}};
use anyhow::Result;

pub fn execute_dream(engine: &SymbolicEngine) -> Result<Symbol> {{
    // WENDY's generated First-Order Logic inference
    {}
    Ok(Symbol::Constant(1.0))
}}
"#,
            zulu_time, dream_name, symbolic_logic
        );

        fs::write(&file_path, rust_code)
            .context(format!("Failed to materialize dream to {}", file_path))?;

        let mod_content = fs::read_to_string(&self.mod_file).unwrap_or_default();
        let module_decl = format!("pub mod {};", dream_name);
        if !mod_content.contains(&module_decl) {
            fs::OpenOptions::new()
                .append(true)
                .open(&self.mod_file)
                .and_then(|mut f| std::io::Write::write_all(&mut f, format!("\n{}", module_decl).as_bytes()))
                .context("Failed to update dream registry")?;
        }

        if let Err(e) = Command::new("rustfmt").arg(&file_path).status() {
            error!("rustfmt failed on dream file: {}", e);
        }
        if let Err(e) = Command::new("rustfmt").arg(&self.mod_file).status() {
            error!("rustfmt failed on mod file: {}", e);
        }

        info!(timestamp = %zulu_time, "Dream materialized. Triggering Git Automator.");
        self.trigger_git_automator(dream_name)?;

        Ok(())
    }

    fn trigger_git_automator(&self, _dream_name: &str) -> Result<()> {
        let status = Command::new("bash")
            .arg("scripts/wendy-dream-runner.sh")
            .status()
            .context("Failed to execute Git Automator")?;

        if !status.success() {
            error!("Git Automator failed with status: {}", status);
            anyhow::bail!("Git push failed");
        }
        Ok(())
    }
}
