CONTAINER_DIR = Path("reports/pico_containers")

def plan_pipeline(goal_text):
    """
    The Planner: Analyzes the goal and decides which agents are needed.
    If a required capability doesn't exist, it spawns it on the fly.
    """
    print(f"[PLANNER] Analyzing goal: {goal_text}")
    
    # Base pipeline
    pipeline = ["forage", "literature", "critic"]
    
    # Detect required capabilities from the goal text
    goal_lower = goal_text.lower()
    
    if "satellite" in goal_lower or "radar" in goal_lower or "space" in goal_lower:
        capability = "satellite"
    elif "genomic" in goal_lower or "dna" in goal_lower or "sequence" in goal_lower:
        capability = "genomic"
    elif "economic" in goal_lower or "market" in goal_lower:
        capability = "economic"
    else:
        capability = None
        
    if capability:
        agent_file = Path(f"{capability}_agent.py")
        if not agent_file.exists():
            print(f"[PLANNER] Capability '{capability}' missing. Spawning new agent mid-chain...")
            spawn_agent_code(capability, agent_file)
        
        # Insert the new capability right before the critic
        pipeline.insert(-1, capability)
        print(f"[PLANNER] Injected '{capability}' into pipeline.")
        
    # Always end with intelligence audit
    pipeline.append("intelligence")
    
    return pipeline

